// Fetches Chiron's apparent geocentric ecliptic longitude of date (JPL Horizons, quantity 31) every 5 days,
// 1900–2100, and writes it delta-encoded in units of 0.0001°. src/index.ts interpolates between samples.
// Usage: node scripts/build-data.ts  (rewrites src/data.ts)
export {};
const START = '1900-01-01', STOP = '2100-12-31', STEP = 5;
const q = new URLSearchParams({
  format: 'json', COMMAND: "'2060;'", EPHEM_TYPE: 'OBSERVER', CENTER: "'500@399'", START_TIME: `'${START}'`, STOP_TIME: `'${STOP}'`,
  STEP_SIZE: `'${STEP}d'`, QUANTITIES: "'31'", TIME_TYPE: "'UT'", CSV_FORMAT: "'YES'",
});
const r = await (await fetch('https://ssd.jpl.nasa.gov/api/horizons.api?' + q)).json() as { result: string };
const lines = r.result.split('$$SOE')[1].split('$$EOE')[0].trim().split('\n');
const lons = lines.map(l => +l.split(',')[3]);
if (lons.some(Number.isNaN)) throw new Error('unexpected Horizons output');
// Deltas between rounded values, so decoding does not drift; wrapped into (−180°, 180°].
const units = lons.map(x => Math.round(x * 1e4));
const d = units.slice(1).map((u, i) => { let x = u - units[i]; if (x > 1_800_000) x -= 3_600_000; if (x <= -1_800_000) x += 3_600_000; return x; });
const solution = /Soln\.date:\s*(\S+)/.exec(r.result)?.[1];
const out = JSON.stringify({
  source: `NASA JPL Horizons API, 2060 Chiron, observer ecliptic longitude of date (quantity 31), geocentric; solution ${solution}`,
  generated: new Date().toISOString().slice(0, 10), start: `${START}T00:00:00Z`, stepDays: STEP, unit: 1e-4, first: units[0], d,
});
const { writeFileSync } = await import('node:fs');
writeFileSync(new URL('../src/data.ts', import.meta.url), `// Generated by scripts/build-data.ts from the NASA JPL Horizons API. Do not edit.\nexport default ${out};\n`);
